export type TandemScene = keyof typeof TANDEM_SCRIPTS;
export type TandemLine = TandemScene | `${TandemScene}--${number}`;
export type TandemMood = "listen" | "speak" | "point" | "celebrate" | "concern";
export type TandemBeat = { line: TandemLine; text: string; pause: number };
export function sceneBeats(scene: TandemScene): TandemBeat[] {
  return TANDEM_SCRIPTS[scene].map((text, index) => ({
    line: index === 0 ? scene : `${scene}--${index + 1}` as TandemLine,
    text,
    // A short listening beat gives a thought room before the response.
    pause: scene.includes("hint") ? 500 : index === 0 ? 800 : 1100,
  }));
}
export const TANDEM_LINES = Object.fromEntries(
  (Object.keys(TANDEM_SCRIPTS) as TandemScene[]).flatMap(scene =>
    sceneBeats(scene).map(beat => [beat.line, beat.text])),
) as Record<TandemLine, string>;
